  const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

  function requestJSON(method, url, payload, timeoutMs) {
    return new Promise((resolve, reject) => {
      const timeout = timeoutMs || 30000;
      const headers = payload ? { 'Content-Type': 'application/json' } : {};
      const body = payload ? JSON.stringify(payload) : undefined;

      if (typeof GM_xmlhttpRequest === 'function') {
        GM_xmlhttpRequest({
          method,
          url,
          headers,
          data: body,
          timeout,
          onload: (r) => {
            let data = null;
            try { data = JSON.parse(r.responseText || '{}'); } catch (_) {}
            if (r.status >= 200 && r.status < 300) resolve(data || {});
            else reject(httpError(data, r.status));
          },
          onerror: () => reject(new Error('network')),
          ontimeout: () => reject(new Error('timeout')),
        });
        return;
      }

      const ctrl = new AbortController();
      const timer = setTimeout(() => ctrl.abort(), timeout);
      fetch(url, {
        method,
        headers,
        body,
        signal: ctrl.signal,
      }).then(async (r) => {
        clearTimeout(timer);
        const data = await r.json().catch(() => ({}));
        if (!r.ok) throw httpError(data, r.status);
        resolve(data);
      }).catch((e) => {
        clearTimeout(timer);
        reject(e);
      });
    });
  }

