  const stripAnswerNoise = (s) => cleanText(s, 2000)
    .replace(/^(?:final\s+)?(?:answer|correct answer|đáp án|trả lời)\s*[:：-]\s*/i, '')
    .replace(/^["'`“”]+|["'`“”]+$/g, '')
