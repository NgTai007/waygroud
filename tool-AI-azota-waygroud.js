  function setPanel(text, onAI, aiLabel) {
    const p = ensurePanel();
    const hasText = !!text;
    const hasAI = typeof onAI === 'function';

    if (!hasText && !hasAI) {
      p.hidden = true;
      return;
    }

    p.hidden = hiddenByToggle;
    panelLabel.textContent = hasText ? 'Đáp án' : 'Thiếu đáp án';
    panelAnswer.textContent = text || '';
    panelAnswer.style.display = hasText ? '' : 'none';
    panelAi.hidden = !hasAI;
    if (hasAI) panelAi.textContent = aiLabel || 'AI giải';
    panelAi.onclick = hasAI ? (e) => {
      e.preventDefault();
      e.stopPropagation();
      onAI();
    } : null;
  }

