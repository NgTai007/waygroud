  function markAzota(q, answer) {
    if (!q || !q.isConnected) return false;
    const items = Array.from(q.querySelectorAll('.item-answer'));
    const expected = toList(answer);
    if (!items.length || !expected.length) return false;

    const rows = items.map((item) => ({
      item,
      text: normOption(
        (item.querySelector('.answer-content') || item).textContent || ''
      ),
    }));

    const hits = [];
    for (const a of expected) {
      const found = rows.filter((r) => r.text === normOption(a));
      if (found.length !== 1) {
        clearAzotaMarks(q);
        return false;
      }
      hits.push(found[0].item);
    }

    clearAzotaMarks(q);
    hits.forEach((item) => item.setAttribute('data-study-hit', '1'));
    return true;
  }

