  function recallAI(ctx) {
    const mem = aiMemory.get(memoryKey(ctx));
    if (mem != null) return mem;
    if (ctx.qid) {
      const byQid = questionMemory.get((ctx.site || '') + ':qid:' + ctx.qid);
      if (byQid != null) return byQid;
    }
    const cached = readCache(cacheKey(ctx));
    return cached && cached.a != null ? cached.a : null;
  }

  function readCache(key) {
    try {
      const raw = store.get(key);
      if (!raw) return null;
      const d = JSON.parse(raw);
      const ttl = d.a ? 30 * 864e5 : 36e5;
      if (!d || Date.now() - d.t > ttl) return null;
      return d;
    } catch (_) {
      return null;
    }
  }

  function writeCache(key, answer, confidence) {
    try {
      store.set(key, JSON.stringify({ a: answer, c: confidence, t: Date.now() }));
    } catch (_) {}
  }

  const httpError = (data, status) => {
    const detail = data && data.error;
    const message = typeof detail === 'string'
      ? detail
      : (detail && detail.message) || (data && data.detail) || '';
    return new Error('HTTP ' + status + (message ? ': ' + message : ''));
  };

  const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

  function postJSON(url, payload) {
    return new Promise((resolve, reject) => {
      if (typeof GM_xmlhttpRequest === 'function') {
        GM_xmlhttpRequest({
          method: 'POST',
          url,
          headers: { 'Content-Type': 'application/json' },
          data: JSON.stringify(payload),
          timeout: 30000,
          onload: (r) => {
            let data = null;
            try { data = JSON.parse(r.responseText || '{}'); } catch (_) {}
            if (r.status >= 200 && r.status < 300) resolve(data || {});
            else reject(httpError(data, r.status));
          },
          onerror: () => reject(new Error('network')),
          ontimeout: () => reject(new Error('timeout')),
        });
        return;
      }

      const ctrl = new AbortController();
      const timer = setTimeout(() => ctrl.abort(), 30000);
      fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
        signal: ctrl.signal,
      }).then(async (r) => {
        clearTimeout(timer);
        const data = await r.json().catch(() => ({}));
        if (!r.ok) throw httpError(data, r.status);
        resolve(data);
      }).catch((e) => {
        clearTimeout(timer);
        reject(e);
      });
    });
  }

